def build_cache(
    base: nn.Module,
    loader: DataLoader,
    thresholds: np.ndarray,
    device: torch.device,
    risk_module,
) -> dict[str, Any]:
    risk_feature_parts = []
    base_parts = []
    truth_parts = []
    target_index_parts = []
    target_slot_parts = []

    event_ids = []
    repeats = []

    base.eval()

    with torch.inference_mode():
        for batch in loader:
            truth = (
                batch[
                    "target_log"
                ]
                .numpy()
            )

            (
                base_prediction,
                risk_feature,
            ) = (
                risk_module
                .cross_attention_base_context(
                    base,
                    batch[
                        "input_waveforms"
                    ].to(
                        device
                    ),
                    batch[
                        "input_features"
                    ].to(
                        device
                    ),
                    batch[
                        "target_features"
                    ].to(
                        device
                    ),
                )
            )

            risk_feature_parts.append(
                risk_feature
                .cpu()
                .numpy()
            )

            base_parts.append(
                base_prediction
                .cpu()
                .numpy()
            )

            truth_parts.append(
                truth
            )

            target_index_parts.append(
                batch[
                    "target_station_index"
                ].numpy()
            )

            target_slot_parts.append(
                batch[
                    "target_slot"
                ].numpy()
            )

            batch_event_ids = list(
                batch[
                    "event_id"
                ]
            )

            batch_repeats = (
                batch[
                    "repeat"
                ]
                .numpy()
            )

            for b in range(
                truth.shape[
                    0
                ]
            ):
                for _ in range(
                    truth.shape[
                        1
                    ]
                ):
                    event_ids.append(
                        str(
                            batch_event_ids[
                                b
                            ]
                        )
                    )

                    repeats.append(
                        int(
                            batch_repeats[
                                b
                            ]
                        )
                    )

    risk_feature = np.concatenate(
        risk_feature_parts,
        axis=0,
    ).reshape(
        -1,
        risk_feature_parts[
            0
        ].shape[
            -1
        ],
    )

    base_prediction = np.concatenate(
        base_parts,
        axis=0,
    ).reshape(
        -1,
        2,
    )

    truth = np.concatenate(
        truth_parts,
        axis=0,
    ).reshape(
        -1,
        2,
    )

    target_indices = np.concatenate(
        target_index_parts,
        axis=0,
    ).reshape(
        -1
    )

    target_slots = np.concatenate(
        target_slot_parts,
        axis=0,
    ).reshape(
        -1
    )

    tail = (
        truth
        >= thresholds[
            None,
            :,
        ]
    )

    under = (
        (
            base_prediction
            - truth
        )
        <= SEVERE_UNDER_THRESHOLD
    )

    return {
        "risk_feature": risk_feature.astype(
            np.float32
        ),
        "base": base_prediction.astype(
            np.float64
        ),
        "truth": truth.astype(
            np.float64
        ),
        "tail": tail.astype(
            bool
        ),
        "under": under.astype(
            bool
        ),
        "event_id": np.asarray(
            event_ids,
            dtype=object,
        ),
        "repeat": np.asarray(
            repeats,
            dtype=np.int64,
        ),
        "target_station_index": (
            target_indices.astype(
                np.int64
            )
        ),
        "target_slot": (
            target_slots.astype(
                np.int64
            )
        ),
    }


