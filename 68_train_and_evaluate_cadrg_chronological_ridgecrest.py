def bool_array(
    series: pd.Series,
) -> np.ndarray:
    if pd.api.types.is_bool_dtype(
        series
    ):
        return series.to_numpy(
            dtype=bool
        )

    return (
        series.astype(str)
        .str.strip()
        .str.lower()
        .isin(
            {
                "true",
                "1",
                "yes",
                "y",
                "t",
            }
        )
        .to_numpy(
            dtype=bool
        )
    )


def element_metric(
    truth: np.ndarray,
    prediction: np.ndarray,
    metric: str,
) -> np.ndarray:
    residual = (
        prediction
        - truth
    )

    absolute = np.abs(
        residual
    )

    if metric == "mae":
        return absolute

    if metric == "bias":
        return residual

    if metric == "factor2":
        return (
            absolute
            <= LOG10_FACTOR_2
        ).astype(
            float
        )

    if metric == "factor3":
        return (
            absolute
            <= LOG10_FACTOR_3
        ).astype(
            float
        )

    if metric == "under05":
        return (
            residual
            <= SEVERE_UNDER_THRESHOLD
        ).astype(
            float
        )

    raise ValueError(
        metric
    )


def event_values(
    frame: pd.DataFrame,
    truth_column: str,
    prediction_column: str,
    metric: str,
) -> pd.Series:
    values = element_metric(
        frame[
            truth_column
        ].to_numpy(
            float
        ),
        frame[
            prediction_column
        ].to_numpy(
            float
        ),
        metric,
    )

    work = frame[
        [
            "event_id",
            "repeat",
        ]
    ].copy()

    work[
        "value"
    ] = values

    event_repeat = (
        work.groupby(
            [
                "event_id",
                "repeat",
            ],
            sort=False,
        )[
            "value"
        ]
        .mean()
        .reset_index()
    )

    return (
        event_repeat.groupby(
            "event_id",
            sort=False,
        )[
            "value"
        ]
        .mean()
    )


def metric_table(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    rows = []

    models = {
        "cross_attention_base": (
            "base"
        ),
        "ca_drg": (
            "final"
        ),
    }

    for (
        split_name,
        split_frame,
    ) in predictions.groupby(
        "split",
        sort=False,
    ):
        for (
            model_name,
            prefix,
        ) in models.items():
            for quantity in (
                "pga",
                "pgv",
            ):
                populations = {
                    "overall": (
                        np.ones(
                            len(
                                split_frame
                            ),
                            dtype=bool,
                        )
                    ),
                    "high_motion_tail": (
                        bool_array(
                            split_frame[
                                f"is_tail_{quantity}"
                            ]
                        )
                    ),
                }

                for (
                    population,
                    mask,
                ) in populations.items():
                    subset = (
                        split_frame.loc[
                            mask
                        ].copy()
                    )

                    if subset.empty:
                        continue

                    for metric in (
                        "mae",
                        "bias",
                        "factor2",
                        "factor3",
                        "under05",
                    ):
                        event_metric = (
                            event_values(
                                subset,
                                f"true_log10_{quantity}",
                                f"{prefix}_log10_{quantity}",
                                metric,
                            )
                        )

                        rows.append(
                            {
                                "split": (
                                    split_name
                                ),
                                "model": (
                                    model_name
                                ),
                                "quantity": (
                                    quantity
                                ),
                                "population": (
                                    population
                                ),
                                "metric": (
                                    metric
                                ),
                                "value": float(
                                    event_metric.mean()
                                ),
                                "n_events": int(
                                    len(
                                        event_metric
                                    )
                                ),
                                "n_target_rows": int(
                                    len(
                                        subset
                                    )
                                ),
                            }
                        )

    return pd.DataFrame(
        rows
    )


def cadrg_minus_base_table(
    predictions: pd.DataFrame,
) -> pd.DataFrame:
    rows = []

    for (
        split_name,
        split_frame,
    ) in predictions.groupby(
        "split",
        sort=False,
    ):
        for quantity in (
            "pga",
            "pgv",
        ):
            for population in (
                "overall",
                "high_motion_tail",
            ):
                subset = split_frame

                if (
                    population
                    == "high_motion_tail"
                ):
                    subset = (
                        split_frame.loc[
                            bool_array(
                                split_frame[
                                    f"is_tail_{quantity}"
                                ]
                            )
                        ].copy()
                    )

                if subset.empty:
                    continue

                for metric in (
                    "mae",
                    "bias",
                    "factor2",
                    "under05",
                ):
                    base = event_values(
                        subset,
                        f"true_log10_{quantity}",
                        f"base_log10_{quantity}",
                        metric,
                    )

                    final = event_values(
                        subset,
                        f"true_log10_{quantity}",
                        f"final_log10_{quantity}",
                        metric,
                    )

                    common = (
                        base.index
                        .intersection(
                            final.index
                        )
                    )

                    delta = (
                        final.loc[
                            common
                        ]
                        - base.loc[
                            common
                        ]
                    )

                    base_value = float(
                        base.loc[
                            common
                        ].mean()
                    )

                    final_value = float(
                        final.loc[
                            common
                        ].mean()
                    )

                    record = {
                        "split": (
                            split_name
                        ),
                        "quantity": (
                            quantity
                        ),
                        "population": (
                            population
                        ),
                        "metric": (
                            metric
                        ),
                        "n_paired_events": int(
                            len(
                                common
                            )
                        ),
                        "base_value": (
                            base_value
                        ),
                        "ca_drg_value": (
                            final_value
                        ),
                        "mean_delta_cadrg_minus_base": float(
                            delta.mean()
                        ),
                        "median_delta_cadrg_minus_base": float(
                            delta.median()
                        ),
                    }

                    if metric == "mae":
                        record[
                            "relative_change_percent"
                        ] = float(
                            100.0
                            * (
                                final_value
                                - base_value
                            )
                            / max(
                                abs(
                                    base_value
                                ),
                                1e-12,
                            )
                        )

                    if metric in {
                        "factor2",
                        "under05",
                    }:
                        record[
                            "delta_percentage_points"
                        ] = float(
                            100.0
                            * (
                                final_value
                                - base_value
                            )
                        )

                    rows.append(
                        record
                    )

    return pd.DataFrame(
        rows
    )


