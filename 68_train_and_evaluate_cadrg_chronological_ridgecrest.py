# Relative-bias feasibility
# ---------------------------------------------------------------------

def relative_bias_status(
    candidate: dict[str, float],
    base: dict[str, float],
    overall_budget: float,
    non_tail_budget: float,
    bias_margin: float,
) -> dict[str, Any]:
    result = {}
    conditions = []

    for quantity in (
        "pga",
        "pgv",
    ):
        overall_delta = (
            candidate[
                f"overall_mae_{quantity}"
            ]
            - base[
                f"overall_mae_{quantity}"
            ]
        )

        non_tail_delta = (
            candidate[
                f"non_tail_mae_{quantity}"
            ]
            - base[
                f"non_tail_mae_{quantity}"
            ]
        )

        tail_delta = (
            candidate[
                f"tail_mae_{quantity}"
            ]
            - base[
                f"tail_mae_{quantity}"
            ]
        )

        tail_u05_delta = (
            candidate[
                f"tail_under05_{quantity}"
            ]
            - base[
                f"tail_under05_{quantity}"
            ]
        )

        base_bias = float(
            base[
                f"bias_{quantity}"
            ]
        )

        candidate_bias = float(
            candidate[
                f"bias_{quantity}"
            ]
        )

        relative_bias_limit = (
            abs(
                base_bias
            )
            + float(
                bias_margin
            )
        )

        result[
            f"overall_delta_{quantity}"
        ] = overall_delta

        result[
            f"non_tail_delta_{quantity}"
        ] = non_tail_delta

        result[
            f"tail_delta_{quantity}"
        ] = tail_delta

        result[
            f"tail_under05_delta_{quantity}"
        ] = tail_u05_delta

        result[
            f"relative_bias_limit_{quantity}"
        ] = relative_bias_limit

        result[
            f"pass_overall_{quantity}"
        ] = bool(
            overall_delta
            <= float(
                overall_budget
            )
        )

        result[
            f"pass_non_tail_{quantity}"
        ] = bool(
            non_tail_delta
            <= float(
                non_tail_budget
            )
        )

        result[
            f"pass_relative_bias_{quantity}"
        ] = bool(
            abs(
                candidate_bias
            )
            <= relative_bias_limit
        )

        conditions.extend(
            [
                result[
                    f"pass_overall_{quantity}"
                ],
                result[
                    f"pass_non_tail_{quantity}"
                ],
                result[
                    f"pass_relative_bias_{quantity}"
                ],
            ]
        )

    result[
        "feasible"
    ] = bool(
        all(
            conditions
        )
    )

    return result


