"""
68_train_and_evaluate_cadrg_chronological_ridgecrest.py

Step 5: Chronological extrapolation + Ridgecrest sequence-level OOD
for the final CA-DRG model.

Chronological protocol
----------------------
train:
    2010-2018
validation:
    2019 non-Ridgecrest + 2020
test:
    2021-2024
ridgecrest_ood:
    complete held-out 2019 Ridgecrest sequence

The split is supplied by the existing time-clean manifest:
    scenario_t0_5s_k5_time_clean.csv
with:
    split_time_clean

Model
-----
A2-time:
    Cross-Attention Base

A6-time:
    CA-DRG
    y_final = y_base + p_under * p_tail**gamma * Delta

Selection protocol
------------------
1. Retrain Cross-Attention using chronological TRAIN only.
2. Select Base checkpoint using chronological VALIDATION only.
3. Reuse the TRAIN-only chronological Q90 threshold JSON generated by the
   previous clean-time pipeline for the SAME split/task.
4. Freeze Base.
5. Train Dual-Risk head on chronological TRAIN only.
6. Jointly select head epoch + gamma on 20-repeat chronological VALIDATION.
7. OOD/shift-aware preservation guards:
       overall MAE increase <= 0.005 for both PGA/PGV
       non-tail MAE increase <= 0.003 for both PGA/PGV
       |bias_candidate| <= |bias_base| + 0.005 for both PGA/PGV
8. If the selected gamma is not at the upper grid boundary, freeze everything.
9. Evaluate ONCE on:
       (a) 2021-2024 chronological test
       (b) full Ridgecrest sequence-level OOD

No 2021-2024 or Ridgecrest event is used for checkpoint/gamma selection.

Canonical metric aggregation
----------------------------
targets -> repeats -> events

Required local modules
----------------------
45_phase2_strong_baseline_suite.py
60_train_cross_attention_dual_risk_joint_selection.py
"""

