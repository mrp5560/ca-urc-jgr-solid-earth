def train_chronological_base(
    baseline_module,
    args,
    device: torch.device,
    out_dir: Path,
) -> tuple[
    nn.Module,
    dict[str, Any],
]:
    train_dataset = make_dataset(
        baseline_module,
        args,
        args.train_label,
        training=True,
        repeats=1,
    )

    validation_dataset = make_dataset(
        baseline_module,
        args,
        args.validation_label,
        training=False,
        repeats=args.base_validation_repeats,
    )

    generator = torch.Generator()
    generator.manual_seed(
        args.seed
    )

    train_loader = make_loader(
        train_dataset,
        args,
        device,
        shuffle=True,
        generator=generator,
    )

    validation_loader = make_loader(
        validation_dataset,
        args,
        device,
        shuffle=False,
    )

    model = baseline_module.make_model(
        "cross_attention",
        args.hidden_dim,
        args.attention_heads,
        50.0,
    ).to(
        device
    )

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.base_learning_rate,
        weight_decay=args.base_weight_decay,
    )

    scheduler = (
        torch.optim.lr_scheduler
        .ReduceLROnPlateau(
            optimizer,
            mode="min",
            factor=0.5,
            patience=args.base_lr_patience,
            min_lr=args.base_minimum_learning_rate,
        )
    )

    base_dir = (
        out_dir
        / "cross_attention_base"
    )

    base_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    best_path = (
        base_dir
        / "best_model.pt"
    )

    best_score = np.inf
    best_epoch = 0
    stale = 0
    history = []

    print(
        "\n=== Step 5A: chronological "
        "Cross-Attention Base training ==="
    )

    print(
        f"Train events              : "
        f"{len(train_dataset.frame)}"
    )

    print(
        f"Validation events         : "
        f"{len(validation_dataset.frame)}"
    )

    print(
        f"Validation repeats        : "
        f"{args.base_validation_repeats}"
    )

    print(
        f"Parameters                : "
        f"{sum(p.numel() for p in model.parameters()):,}"
    )

    for epoch in range(
        1,
        args.base_epochs
        + 1,
    ):
        train_dataset.set_epoch(
            epoch
        )

        train_loss = (
            baseline_module.train_epoch(
                model,
                train_loader,
                optimizer,
                device,
            )
        )

        val_frame = (
            baseline_module.predict_model(
                model,
                validation_loader,
                device,
            )
        )

        val_pga = (
            baseline_module.event_balanced_mae(
                val_frame,
                "pga",
                "pred_log10_pga",
            )
        )

        val_pgv = (
            baseline_module.event_balanced_mae(
                val_frame,
                "pgv",
                "pred_log10_pgv",
            )
        )

        score = 0.5 * (
            val_pga
            + val_pgv
        )

        scheduler.step(
            score
        )

        learning_rate = float(
            optimizer.param_groups[
                0
            ][
                "lr"
            ]
        )

        history.append(
            {
                "epoch": epoch,
                "train_loss": train_loss,
                "validation_mae_pga": val_pga,
                "validation_mae_pgv": val_pgv,
                "validation_score": score,
                "learning_rate": learning_rate,
            }
        )

        pd.DataFrame(
            history
        ).to_csv(
            base_dir
            / "history.csv",
            index=False,
        )

        print(
            f"Base epoch {epoch:03d} | "
            f"train={train_loss:.4f} | "
            f"val PGA={val_pga:.4f} | "
            f"PGV={val_pgv:.4f} | "
            f"score={score:.4f} | "
            f"lr={learning_rate:.2e}"
        )

        if (
            score
            < best_score
            - args.base_minimum_delta
        ):
            best_score = (
                score
            )
            best_epoch = (
                epoch
            )
            stale = 0

            torch.save(
                {
                    "variant": (
                        "cross_attention"
                    ),
                    "model_state": (
                        model.state_dict()
                    ),
                    "epoch": (
                        epoch
                    ),
                    "validation_mae_pga": (
                        val_pga
                    ),
                    "validation_mae_pgv": (
                        val_pgv
                    ),
                    "validation_score": (
                        score
                    ),
                    "chronological_training": (
                        True
                    ),
                    "args": vars(
                        args
                    ),
                },
                best_path,
            )

        else:
            stale += 1

        if (
            stale
            >= args.base_early_stopping_patience
        ):
            print(
                "Base early stopping at "
                f"epoch {epoch}; "
                f"best epoch={best_epoch}"
            )
            break

    checkpoint = load_checkpoint(
        best_path,
        device,
    )

    model.load_state_dict(
        checkpoint[
            "model_state"
        ],
        strict=True,
    )

    model.eval()

    summary = {
        "best_epoch": int(
            checkpoint[
                "epoch"
            ]
        ),
        "validation_mae_pga": float(
            checkpoint[
                "validation_mae_pga"
            ]
        ),
        "validation_mae_pgv": float(
            checkpoint[
                "validation_mae_pgv"
            ]
        ),
        "validation_score": float(
            checkpoint[
                "validation_score"
            ]
        ),
        "train_events": int(
            len(
                train_dataset.frame
            )
        ),
        "validation_events": int(
            len(
                validation_dataset.frame
            )
        ),
        "checkpoint": str(
            best_path.resolve()
        ),
    }

    (
        base_dir
        / "base_selection_summary.json"
    ).write_text(
        json.dumps(
            summary,
            indent=2,
        ),
        encoding="utf-8",
    )

    print(
        "\nSelected chronological "
        "Cross-Attention Base:"
    )

    print(
        f"  epoch="
        f"{summary['best_epoch']}"
    )

    print(
        "  val PGA/PGV="
        f"{summary['validation_mae_pga']:.4f}/"
        f"{summary['validation_mae_pgv']:.4f}"
    )

    return (
        model,
        summary,
    )


