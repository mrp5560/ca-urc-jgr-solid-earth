def plot_ecdf_panel(ax: plt.Axes, unique_pairs: pd.DataFrame) -> None:
    for quantity in ("pga", "pgv"):
        subset = unique_pairs.loc[unique_pairs[f"is_tail_{quantity}"]]
        values = pd.to_numeric(
            subset[f"lead_to_{quantity}_peak_sec"], errors="coerce"
        ).to_numpy(float)
        values = np.sort(values[np.isfinite(values)])
        if values.size == 0:
            continue
        y = np.arange(1, values.size + 1, dtype=float) / values.size
        ax.step(values, y, where="post", linewidth=1.55, label=quantity.upper())
    for reference in (2.0, 5.0, 10.0):
        ax.axvline(reference, linestyle=":", linewidth=0.75, alpha=0.55)
    ax.set_xlabel("Time to remaining peak after the 5-s snapshot (s)")
    ax.set_ylabel("Cumulative fraction")
    ax.set_ylim(0.0, 1.0)
    ax.legend(frameon=False, loc="lower right")
    ax.set_title("Many high-motion peaks remain after the 5-s snapshot", loc="left", fontweight="bold", fontsize=7.8)
    style_axis(ax)


def plot_latency_panel(ax: plt.Axes, latency: pd.DataFrame) -> None:
    for quantity in ("pga", "pgv"):
        for definition, linestyle, suffix in (
            ("time_to_remaining_peak", "-", "peak"),
            ("time_to_highmotion_threshold_crossing", "--", "threshold crossing"),
        ):
            subset = latency.loc[
                latency["quantity"].eq(quantity)
                & latency["lead_definition"].eq(definition)
            ].sort_values("assumed_total_latency_sec")
            if subset.empty:
                continue
            ax.plot(
                subset["assumed_total_latency_sec"],
                100.0 * subset["fraction_positive_net_lead"],
                marker="o" if definition == "time_to_remaining_peak" else "s",
                linestyle=linestyle,
                linewidth=1.35,
                markersize=3.6,
                label=f"{quantity.upper()} to {suffix}",
            )
    ax.set_xlabel("Assumed total system latency (s)")
    ax.set_ylabel("Targets with positive net lead (%)")
    ax.set_ylim(0.0, 102.0)
    ax.legend(frameon=False, fontsize=6.4, ncol=2, loc="lower left")
    ax.set_title("System latency reduces positive warning lead", loc="left", fontweight="bold", fontsize=7.8)
    style_axis(ax)


def plot_metric_by_bin(
    ax: plt.Axes,
    metrics: pd.DataFrame,
    quantity: str,
    metric: str,
    title: str,
    ylabel: str,
    percent: bool = False,
) -> None:
    subset = metrics.loc[
        metrics["quantity"].eq(quantity)
        & metrics["metric"].eq(metric)
        & metrics["display_eligible"]
    ].copy()
    order = [label for label in LEAD_BIN_ORDER if label in set(subset["lead_bin"])]
    x = np.arange(len(order), dtype=float)
    offsets = {"cross_attention": -0.08, "ca_urc": 0.08}
    for model in ("cross_attention", "ca_urc"):
        values: list[float] = []
        lows: list[float] = []
        highs: list[float] = []
        for lead_bin in order:
            row = subset.loc[subset["lead_bin"].eq(lead_bin)]
            if len(row) != 1:
                values.append(np.nan)
                lows.append(np.nan)
                highs.append(np.nan)
                continue
            record = row.iloc[0]
            value = float(record[f"{model}_value"])
            low = float(record[f"{model}_ci_lower"])
            high = float(record[f"{model}_ci_upper"])
            if percent:
                value *= 100.0
                low *= 100.0
                high *= 100.0
            values.append(value)
            lows.append(low)
            highs.append(high)
        values_array = np.asarray(values, dtype=float)
        low_array = np.asarray(lows, dtype=float)
        high_array = np.asarray(highs, dtype=float)
        yerr = np.vstack([values_array - low_array, high_array - values_array])
        ax.errorbar(
            x + offsets[model],
            values_array,
            yerr=yerr,
            marker="o" if model == "cross_attention" else "s",
            linewidth=1.25,
            markersize=3.6,
            capsize=2.2,
            label=MODEL_LABELS[model],
        )
    ax.set_xticks(x)
    ax.set_xticklabels([f"{label}\ns" for label in order])
    ax.set_xlabel("Time to remaining peak")
    ax.set_ylabel(ylabel)
    ax.set_title(title, loc="left", fontweight="bold", fontsize=7.8)
    style_axis(ax, grid_axis="y")

    # Event counts are identical for the two paired models.
    counts = []
    for lead_bin in order:
        row = subset.loc[subset["lead_bin"].eq(lead_bin)]
        counts.append(int(row.iloc[0]["n_events"]) if len(row) == 1 else 0)
    ymin, ymax = ax.get_ylim()
    ax.set_ylim(ymin, ymax + 0.04 * max(ymax - ymin, 1e-6))
    for xx, count in zip(x, counts):
        ax.text(
            xx,
            0.985,
            f"n={count}",
            transform=ax.get_xaxis_transform(),
            ha="center",
            va="top",
            fontsize=5.9,
        )


