    parser.add_argument(
        "--predictions",
        default=(
            "runs/cadrg_gate_ablation_A3_A5/"
            "locked_test_ablation_predictions.csv"
        ),
    )
    parser.add_argument(
        "--lead-times",
        default=(
            "runs/phase2_warning_lead_time/"
            "unique_event_station_lead_times.csv"
        ),
    )
    parser.add_argument(
        "--manifest",
        default="model_manifests/scenario_t0_5s_k5_linux.csv",
    )
    parser.add_argument("--split-column", default="split_grouped")
    parser.add_argument("--test-label", default="test")
    parser.add_argument("--sequence-column", default="sequence_group")
    parser.add_argument("--lead-bin-edges", default="0,1,2,5,10,20")
    parser.add_argument("--latencies", default="0,0.5,1,2")
    parser.add_argument("--minimum-leads", default="0,1,2,5,10")
    parser.add_argument("--minimum-events-per-bin", type=int, default=10)
    parser.add_argument("--bootstrap-repetitions", type=int, default=10000)
    parser.add_argument("--confidence-level", type=float, default=0.95)
    parser.add_argument("--seed", type=int, default=20260713)
    parser.add_argument("--dpi", type=int, default=600)
    parser.add_argument("--out-dir", default="figures/nc_section_2_5")
    parser.add_argument("--skip-locked-audit", action="store_true")
    parser.add_argument("--demo", action="store_true")
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.demo:
        frame, audit = make_demo(args.seed)
    else:
        frame, audit = load_and_merge(
            Path(args.predictions),
            Path(args.lead_times),
            Path(args.manifest),
            args.split_column,
            args.test_label,
            args.sequence_column,
        )
        expected = {
            "prediction_rows": 44800,
            "events": 224,
            "sequence_groups": 22,
            "pga_tail_rows": 1363,
            "pgv_tail_rows": 1485,
            "pga_tail_events": 98,
            "pgv_tail_events": 87,
        }
        problems = [
            f"{key}: observed={audit[key]}, expected={value}"
            for key, value in expected.items()
            if int(audit[key]) != int(value)
        ]
        if problems:
            raise RuntimeError("Locked row-count audit failed:\n  " + "\n  ".join(problems))
        if not args.skip_locked_audit:
            locked_metric_audit(frame)

    unique_pairs = unique_physical_pairs(frame)
    edges = parse_float_list(args.lead_bin_edges)
    latencies = parse_float_list(args.latencies)
    minimum_leads = parse_float_list(args.minimum_leads)

    distribution = lead_distribution_table(unique_pairs)
    latency = latency_sensitivity_table(unique_pairs, latencies)
    metrics = metrics_by_peak_lead(
        frame,
        edges=edges,
        repetitions=args.bootstrap_repetitions,
        confidence=args.confidence_level,
        seed=args.seed,
        minimum_events=args.minimum_events_per_bin,
    )
    effects = minimum_lead_effects(
        frame,
        minimum_leads=minimum_leads,
        repetitions=args.bootstrap_repetitions,
        confidence=args.confidence_level,
        seed=args.seed,
    )

    plot_main_figure(unique_pairs, latency, metrics, out_dir, args.dpi)
    plot_minimum_lead_figure(effects, out_dir, args.dpi)
    save_tables(distribution, latency, metrics, effects, out_dir)
    write_manuscript_numbers(
        distribution,
        latency,
        effects,
        audit,
        out_dir / "Section2_5_manuscript_numbers.txt",
    )
    write_manuscript_draft(
        distribution,
        latency,
        effects,
        audit,
        out_dir / "Section2_5_manuscript_draft.txt",
    )
    write_captions(audit, out_dir)

    edge_audit = pd.DataFrame(
        [
            {
                "quantity": "pga",
                "n_unique_event_station_pairs": int(len(unique_pairs)),
                "n_peak_near_window_end": int(unique_pairs["pga_peak_near_window_end"].sum()),
                "fraction_peak_near_window_end": float(unique_pairs["pga_peak_near_window_end"].mean()),
            },
            {
                "quantity": "pgv",
                "n_unique_event_station_pairs": int(len(unique_pairs)),
                "n_peak_near_window_end": int(unique_pairs["pgv_peak_near_window_end"].sum()),
                "fraction_peak_near_window_end": float(unique_pairs["pgv_peak_near_window_end"].mean()),
            },
        ]
    )
    edge_audit.to_csv(out_dir / "TableS5_future_window_edge_audit.csv", index=False)

    configuration = {
        **vars(args),
        "audit": audit,
        "lead_time_origin": "t0=5-s causal snapshot",
        "physical_distribution_weighting": "unique event-station pairs",
        "metric_hierarchy": "targets -> repeats -> events -> sequence-aware bootstrap",
        "delta_definition": "CA-URC - Cross-Attention Base",
        "high_motion_labels_recomputed": False,
        "model_training_performed": False,
        "model_selection_performed": False,
    }
    (out_dir / "run_configuration.json").write_text(
        json.dumps(configuration, indent=2), encoding="utf-8"
    )

    print("=== NC Section 2.5 warning lead-time analysis ===")
    print(json.dumps(audit, indent=2))
    print("\nHigh-motion physical lead distributions:")
    print(distribution.to_string(index=False))
    print("\nMinimum-lead paired effects:")
    print(effects.loc[effects["metric"].eq("mae")].to_string(index=False))
    print("\nOutputs:")
    for path in sorted(out_dir.iterdir()):
        print(" ", path.resolve())


