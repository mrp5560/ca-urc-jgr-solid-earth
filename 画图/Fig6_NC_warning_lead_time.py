def write_manuscript_draft(
    distribution: pd.DataFrame,
    latency: pd.DataFrame,
    effects: pd.DataFrame,
    audit: dict[str, object],
    out_path: Path,
) -> None:
    """Write a manuscript-ready Section 2.5 populated from the locked outputs."""

    def require_dist(quantity: str, definition: str) -> pd.Series:
        row = get_row(distribution, quantity, definition)
        if row is None:
            raise RuntimeError(f"Missing lead distribution row: {quantity}/{definition}")
        return row

    def require_effect(quantity: str, minimum: float, metric: str) -> pd.Series:
        row = effect_row(effects, quantity, minimum, metric)
        if row is None:
            raise RuntimeError(f"Missing minimum-lead effect row: {quantity}/{minimum}/{metric}")
        return row

    def require_latency(quantity: str, definition: str, latency_sec: float) -> pd.Series:
        row = latency.loc[
            latency["quantity"].eq(quantity)
            & latency["lead_definition"].eq(definition)
            & np.isclose(latency["assumed_total_latency_sec"], latency_sec)
        ]
        if len(row) != 1:
            raise RuntimeError(
                f"Missing latency row: {quantity}/{definition}/{latency_sec}"
            )
        return row.iloc[0]

    pga_peak = require_dist("pga", "time_to_remaining_peak")
    pgv_peak = require_dist("pgv", "time_to_remaining_peak")
    pga_cross = require_dist("pga", "time_to_highmotion_threshold_crossing")
    pgv_cross = require_dist("pgv", "time_to_highmotion_threshold_crossing")

    pga_pos = require_effect("pga", 0.0, "mae")
    pgv_pos = require_effect("pgv", 0.0, "mae")
    pga_5 = require_effect("pga", 5.0, "mae")
    pgv_5 = require_effect("pgv", 5.0, "mae")
    pga_10 = require_effect("pga", 10.0, "mae")
    pgv_10 = require_effect("pgv", 10.0, "mae")

    pga_latency_1 = require_latency("pga", "time_to_remaining_peak", 1.0)
    pgv_latency_1 = require_latency("pgv", "time_to_remaining_peak", 1.0)
    pga_cross_latency_1 = require_latency(
        "pga", "time_to_highmotion_threshold_crossing", 1.0
    )
    pgv_cross_latency_1 = require_latency(
        "pgv", "time_to_highmotion_threshold_crossing", 1.0
    )
    pga_latency_2 = require_latency("pga", "time_to_remaining_peak", 2.0)
    pgv_latency_2 = require_latency("pgv", "time_to_remaining_peak", 2.0)

    def effect_sentence(quantity: str, row: pd.Series, lead_label: str) -> str:
        ci_excludes_zero = float(row["delta_ci_upper"]) < 0.0
        qualifier = (
            "and the confidence interval excluded zero"
            if ci_excludes_zero
            else "although the confidence interval included zero"
        )
        return (
            f"For {quantity}, among targets with {lead_label}, tail MAE changed from "
            f"{row['cross_attention_value']:.3f} for the Cross-Attention Base to "
            f"{row['ca_urc_value']:.3f} for CA-URC (paired difference, "
            f"{row['delta_caurc_minus_base']:+.3f}; 95% confidence interval, "
            f"{row['delta_ci_lower']:+.3f} to {row['delta_ci_upper']:+.3f}; "
            f"n={int(row['n_events'])} earthquakes), {qualifier}."
        )

    positive_lead_supported = (
        float(pga_pos["delta_ci_upper"]) < 0.0
        and float(pgv_pos["delta_ci_upper"]) < 0.0
    )
    section_title = (
        "High-motion-tail improvements persist at positive warning lead times"
        if positive_lead_supported
        else "Physical warning lead times and latency sensitivity of high-motion forecasts"
    )
    concluding_claim = (
        "Its tail-error benefit remained statistically resolved in the positive-lead subsets for both PGA and PGV, supporting prospective warning relevance."
        if positive_lead_supported
        else "Point estimates in the positive-lead subsets remained favourable, but the uncertainty intervals did not resolve an improvement for both quantities; the result should therefore be interpreted as directional evidence rather than definitive prospective validation."
    )

