def dataframe_to_latex(frame: pd.DataFrame, percent_columns: set[str] | None = None) -> str:
    display = frame.copy()
    percent_columns = percent_columns or set()
    for column in display.columns:
        if pd.api.types.is_float_dtype(display[column]):
            if column in percent_columns or column.startswith("fraction_"):
                display[column] = display[column].map(
                    lambda value: "--" if pd.isna(value) else f"{100.0 * value:.1f}\\%"
                )
            else:
                display[column] = display[column].map(
                    lambda value: "--" if pd.isna(value) else f"{value:.3f}"
                )
    return display.to_latex(index=False, escape=False)


