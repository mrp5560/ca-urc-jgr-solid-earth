def require_columns(df: pd.DataFrame, columns: Iterable[str], name: str) -> None:
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise ValueError(f"{name} is missing required columns: {missing}")


def parse_bool(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False).astype(bool)
    text = series.astype(str).str.strip().str.lower()
    mapping = {
        "true": True,
        "false": False,
        "1": True,
        "0": False,
        "yes": True,
        "no": False,
        "y": True,
        "n": False,
        "t": True,
        "f": False,
        "nan": False,
        "none": False,
        "": False,
    }
    unknown = sorted(set(text.unique()).difference(mapping))
    if unknown:
        raise ValueError(f"Cannot parse boolean values: {unknown[:20]}")
    return text.map(mapping).astype(bool)


def parse_float_list(text: str) -> list[float]:
    values = [float(item.strip()) for item in str(text).split(",") if item.strip()]
    if not values:
        raise ValueError("Expected at least one numeric value.")
    return values


def make_lead_bins(values: pd.Series, edges: list[float]) -> pd.Categorical:
    edges = sorted(set(float(value) for value in edges))
    if not np.isclose(edges[0], 0.0):
        raise ValueError("Lead-time bin edges must start at 0 s.")
    bins = edges + [np.inf]
    labels: list[str] = []
    for left, right in zip(edges[:-1], edges[1:]):
        labels.append(f"{left:g}–{right:g}")
    labels.append(f"≥{edges[-1]:g}")
    return pd.cut(
        pd.to_numeric(values, errors="coerce"),
        bins=bins,
        labels=labels,
        right=False,
        include_lowest=True,
        ordered=True,
    )


def load_and_merge(
    predictions_path: Path,
    lead_times_path: Path,
    manifest_path: Path,
    split_column: str,
    test_label: str,
    sequence_column: str,
) -> tuple[pd.DataFrame, dict[str, object]]:
    for path in (predictions_path, lead_times_path, manifest_path):
        if not path.exists():
            raise FileNotFoundError(path)

    pred = pd.read_csv(predictions_path, dtype={"event_id": str})
    lead = pd.read_csv(lead_times_path, dtype={"event_id": str})
    manifest = pd.read_csv(manifest_path, dtype={"event_id": str})

    pred_required = [
        "event_id",
        "repeat",
        "target_station_index",
        "true_log10_pga",
        "true_log10_pgv",
        "is_tail_pga",
        "is_tail_pgv",
        "A2_cross_attention_base_log10_pga",
        "A2_cross_attention_base_log10_pgv",
        "A4_under_only_log10_pga",
        "A4_under_only_log10_pgv",
    ]
    lead_required = [
        "event_id",
        "target_station_index",
        "lead_to_pga_peak_sec",
        "lead_to_pgv_peak_sec",
        "pga_highmotion_crossing_lead_sec",
        "pgv_highmotion_crossing_lead_sec",
        "true_log10_pga_recomputed",
        "true_log10_pgv_recomputed",
        "pga_peak_near_window_end",
        "pgv_peak_near_window_end",
    ]
    require_columns(pred, pred_required, "prediction file")
    require_columns(lead, lead_required, "physical lead-time file")
    require_columns(
        manifest,
        ["event_id", split_column, sequence_column],
        "scenario manifest",
    )

    pred["event_id"] = pred["event_id"].astype(str).str.strip()
    lead["event_id"] = lead["event_id"].astype(str).str.strip()
    manifest["event_id"] = manifest["event_id"].astype(str).str.strip()

    pred["is_tail_pga"] = parse_bool(pred["is_tail_pga"])
    pred["is_tail_pgv"] = parse_bool(pred["is_tail_pgv"])
    lead["pga_peak_near_window_end"] = parse_bool(lead["pga_peak_near_window_end"])
    lead["pgv_peak_near_window_end"] = parse_bool(lead["pgv_peak_near_window_end"])

    prediction_keys = ["event_id", "repeat", "target_station_index"]
    if pred.duplicated(prediction_keys).any():
        raise RuntimeError(f"Prediction rows are not unique on {prediction_keys}.")

    lead_keys = ["event_id", "target_station_index"]
    if lead.duplicated(lead_keys).any():
        raise RuntimeError(f"Physical lead-time rows are not unique on {lead_keys}.")

    test_manifest = manifest.loc[
        manifest[split_column].astype(str).eq(str(test_label)),
        ["event_id", sequence_column],
    ].copy()
    if test_manifest["event_id"].duplicated().any():
        raise RuntimeError("The test manifest contains duplicate event IDs.")
    test_manifest = test_manifest.rename(columns={sequence_column: "sequence_group"})

    merged = pred.merge(lead, on=lead_keys, how="left", validate="many_to_one")
    merged = merged.merge(
        test_manifest,
        on="event_id",
        how="left",
        validate="many_to_one",
    )

    if merged["lead_to_pga_peak_sec"].isna().all():
        raise RuntimeError("No PGA lead times were merged.")
    if merged["lead_to_pgv_peak_sec"].isna().all():
        raise RuntimeError("No PGV lead times were merged.")
    if merged["sequence_group"].isna().any():
        missing = merged.loc[merged["sequence_group"].isna(), "event_id"].unique()[:20]
        raise RuntimeError(f"Missing sequence groups for test events: {missing.tolist()}")

    merged["cross_attention_log10_pga"] = pd.to_numeric(
        merged["A2_cross_attention_base_log10_pga"], errors="coerce"
    )
    merged["cross_attention_log10_pgv"] = pd.to_numeric(
        merged["A2_cross_attention_base_log10_pgv"], errors="coerce"
    )
    merged["ca_urc_log10_pga"] = pd.to_numeric(
        merged["A4_under_only_log10_pga"], errors="coerce"
    )
    merged["ca_urc_log10_pgv"] = pd.to_numeric(
        merged["A4_under_only_log10_pgv"], errors="coerce"
    )

    pga_truth_diff = np.abs(
        pd.to_numeric(merged["true_log10_pga"], errors="coerce").to_numpy(float)
        - pd.to_numeric(merged["true_log10_pga_recomputed"], errors="coerce").to_numpy(float)
    )
    pgv_truth_diff = np.abs(
        pd.to_numeric(merged["true_log10_pgv"], errors="coerce").to_numpy(float)
        - pd.to_numeric(merged["true_log10_pgv_recomputed"], errors="coerce").to_numpy(float)
    )

    audit = {
        "prediction_rows": int(len(pred)),
        "merged_rows": int(len(merged)),
        "events": int(merged["event_id"].nunique()),
        "sequence_groups": int(merged["sequence_group"].nunique()),
        "unique_event_station_pairs": int(
            merged[["event_id", "target_station_index"]].drop_duplicates().shape[0]
        ),
        "pga_tail_rows": int(merged["is_tail_pga"].sum()),
        "pgv_tail_rows": int(merged["is_tail_pgv"].sum()),
        "pga_tail_events": int(merged.loc[merged["is_tail_pga"], "event_id"].nunique()),
        "pgv_tail_events": int(merged.loc[merged["is_tail_pgv"], "event_id"].nunique()),
        "max_abs_truth_diff_pga": float(np.nanmax(pga_truth_diff)),
        "max_abs_truth_diff_pgv": float(np.nanmax(pgv_truth_diff)),
    }
    if audit["max_abs_truth_diff_pga"] > 1e-5 or audit["max_abs_truth_diff_pgv"] > 1e-5:
        raise RuntimeError(f"Prediction/physical truth audit failed: {audit}")

    return merged, audit


def metric_element(truth: np.ndarray, prediction: np.ndarray, metric: str) -> np.ndarray:
    residual = prediction - truth
    if metric == "mae":
        return np.abs(residual)
    if metric == "bias":
        return residual
    if metric == "under05":
        return (residual <= SEVERE_UNDER).astype(float)
    if metric == "factor2":
        return (np.abs(residual) <= LOG10_FACTOR_2).astype(float)
    raise ValueError(metric)


def event_metric_series(
    frame: pd.DataFrame,
    quantity: str,
    model: str,
    metric: str,
) -> pd.Series:
    if frame.empty:
        return pd.Series(dtype=float)
    truth = pd.to_numeric(frame[f"true_log10_{quantity}"], errors="coerce").to_numpy(float)
    pred = pd.to_numeric(frame[f"{model}_log10_{quantity}"], errors="coerce").to_numpy(float)
    values = metric_element(truth, pred, metric)
    work = frame[["event_id", "repeat"]].copy()
    work["value"] = values
    event_repeat = (
        work.groupby(["event_id", "repeat"], sort=False)["value"]
        .mean()
        .reset_index()
    )
    return event_repeat.groupby("event_id", sort=False)["value"].mean()


def locked_metric_audit(frame: pd.DataFrame, tolerance: float = 5e-5) -> None:
    failures: list[str] = []
    for (quantity, population, model, metric), expected in LOCKED_VALUES.items():
        subset = frame if population == "overall" else frame.loc[frame[f"is_tail_{quantity}"]]
        value = float(event_metric_series(subset, quantity, model, metric).mean())
        if not np.isclose(value, expected, atol=tolerance, rtol=0.0):
            failures.append(
                f"{quantity}/{population}/{model}/{metric}: observed={value:.6f}, expected={expected:.6f}"
            )
    if failures:
        raise RuntimeError("Locked prediction audit failed:\n  " + "\n  ".join(failures))


def two_sided_sign_p(distribution: np.ndarray) -> float:
    finite = distribution[np.isfinite(distribution)]
    if finite.size == 0:
        return float("nan")
    lower = (np.sum(finite <= 0.0) + 1.0) / (finite.size + 1.0)
    upper = (np.sum(finite >= 0.0) + 1.0) / (finite.size + 1.0)
    return float(min(1.0, 2.0 * min(lower, upper)))


def bootstrap_paired_event_table(
    event_table: pd.DataFrame,
    repetitions: int,
    confidence: float,
    seed: int,
) -> BootstrapResult:
    require_columns(event_table, ["event_id", "sequence_group", "base", "final"], "event table")
    event_table = event_table.dropna(subset=["base", "final", "sequence_group"]).copy()
    event_table["delta"] = event_table["final"] - event_table["base"]
    n_events = int(len(event_table))
    sequence_names = event_table["sequence_group"].astype(str).unique().tolist()
    n_groups = len(sequence_names)
    if n_events < 2:
        return BootstrapResult(
            base=float(event_table["base"].mean()),
            final=float(event_table["final"].mean()),
            delta=float(event_table["delta"].mean()),
            base_low=float("nan"), base_high=float("nan"),
            final_low=float("nan"), final_high=float("nan"),
            delta_low=float("nan"), delta_high=float("nan"),
            p_two_sided=float("nan"), probability_final_better=float("nan"),
            n_events=n_events, n_sequence_groups=n_groups, mode="insufficient",
        )

    group_indices = [
        np.flatnonzero(event_table["sequence_group"].astype(str).to_numpy() == group)
        for group in sequence_names
    ]
    base_values = event_table["base"].to_numpy(float)
    final_values = event_table["final"].to_numpy(float)
    delta_values = event_table["delta"].to_numpy(float)
    rng = np.random.default_rng(seed)
    boot_base = np.empty(repetitions, dtype=float)
    boot_final = np.empty(repetitions, dtype=float)
    boot_delta = np.empty(repetitions, dtype=float)

    if n_groups >= 2:
        mode = "hierarchical_sequence_event"
        for b in range(repetitions):
            selected_group_positions = rng.integers(0, n_groups, size=n_groups)
            sampled_indices: list[np.ndarray] = []
            for group_position in selected_group_positions:
                idx = group_indices[int(group_position)]
                sampled_indices.append(rng.choice(idx, size=len(idx), replace=True))
            sample = np.concatenate(sampled_indices)
            boot_base[b] = float(base_values[sample].mean())
            boot_final[b] = float(final_values[sample].mean())
            boot_delta[b] = float(delta_values[sample].mean())
    else:
        mode = "event_only_fallback"
        warnings.warn(
            "Only one sequence group contributes to a lead-time subset; "
            "using event-only bootstrap for that subset.",
            RuntimeWarning,
        )
        for b in range(repetitions):
            sample = rng.integers(0, n_events, size=n_events)
            boot_base[b] = float(base_values[sample].mean())
            boot_final[b] = float(final_values[sample].mean())
            boot_delta[b] = float(delta_values[sample].mean())

    alpha = (1.0 - confidence) / 2.0
    q_low, q_high = [100.0 * alpha, 100.0 * (1.0 - alpha)]
    return BootstrapResult(
        base=float(base_values.mean()),
        final=float(final_values.mean()),
        delta=float(delta_values.mean()),
        base_low=float(np.percentile(boot_base, q_low)),
        base_high=float(np.percentile(boot_base, q_high)),
        final_low=float(np.percentile(boot_final, q_low)),
        final_high=float(np.percentile(boot_final, q_high)),
        delta_low=float(np.percentile(boot_delta, q_low)),
        delta_high=float(np.percentile(boot_delta, q_high)),
        p_two_sided=two_sided_sign_p(boot_delta),
        probability_final_better=float(np.mean(boot_delta < 0.0)),
        n_events=n_events,
        n_sequence_groups=n_groups,
        mode=mode,
    )


def event_table_for_subset(
    frame: pd.DataFrame,
    quantity: str,
    metric: str,
) -> pd.DataFrame:
    base = event_metric_series(frame, quantity, "cross_attention", metric)
    final = event_metric_series(frame, quantity, "ca_urc", metric)
    common = base.index.intersection(final.index)
    groups = (
        frame[["event_id", "sequence_group"]]
        .drop_duplicates("event_id")
        .set_index("event_id")["sequence_group"]
    )
    return pd.DataFrame(
        {
            "event_id": common.astype(str),
            "sequence_group": groups.loc[common].astype(str).to_numpy(),
            "base": base.loc[common].to_numpy(float),
            "final": final.loc[common].to_numpy(float),
        }
    )


def unique_physical_pairs(frame: pd.DataFrame) -> pd.DataFrame:
    keys = ["event_id", "target_station_index"]
    consistency_columns = [
        "true_log10_pga",
        "true_log10_pgv",
        "is_tail_pga",
        "is_tail_pgv",
        "lead_to_pga_peak_sec",
        "lead_to_pgv_peak_sec",
        "pga_highmotion_crossing_lead_sec",
        "pgv_highmotion_crossing_lead_sec",
    ]
    for column in consistency_columns:
        counts = frame.groupby(keys, sort=False)[column].nunique(dropna=False)
        if (counts > 1).any():
            raise RuntimeError(
                f"Physical quantity {column!r} is inconsistent across repeats for the same event-station pair."
            )
    keep = keys + consistency_columns + [
        "sequence_group",
        "pga_peak_near_window_end",
        "pgv_peak_near_window_end",
    ]
    return frame[keep].drop_duplicates(keys).reset_index(drop=True)


def lead_distribution_table(unique_pairs: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    for quantity in ("pga", "pgv"):
        tail = unique_pairs.loc[unique_pairs[f"is_tail_{quantity}"]].copy()
        definitions = {
            "time_to_remaining_peak": f"lead_to_{quantity}_peak_sec",
            "time_to_highmotion_threshold_crossing": f"{quantity}_highmotion_crossing_lead_sec",
        }
        for definition, column in definitions.items():
            values = pd.to_numeric(tail[column], errors="coerce").to_numpy(float)
            values = values[np.isfinite(values)]
            if values.size == 0:
                continue
            rows.append(
                {
                    "quantity": quantity,
                    "lead_definition": definition,
                    "n_unique_event_station_pairs_total": int(len(tail)),
                    "n_with_finite_lead": int(values.size),
                    "finite_fraction": float(values.size / max(len(tail), 1)),
                    "median_sec": float(np.median(values)),
                    "p25_sec": float(np.percentile(values, 25)),
                    "p75_sec": float(np.percentile(values, 75)),
                    "p90_sec": float(np.percentile(values, 90)),
                    "fraction_gt_0s": float(np.mean(values > 0.0)),
                    "fraction_ge_1s": float(np.mean(values >= 1.0)),
                    "fraction_ge_2s": float(np.mean(values >= 2.0)),
                    "fraction_ge_5s": float(np.mean(values >= 5.0)),
                    "fraction_ge_10s": float(np.mean(values >= 10.0)),
                }
            )
    return pd.DataFrame(rows)


def latency_sensitivity_table(
    unique_pairs: pd.DataFrame,
    latencies: list[float],
) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    for quantity in ("pga", "pgv"):
        tail = unique_pairs.loc[unique_pairs[f"is_tail_{quantity}"]].copy()
        definitions = {
            "time_to_remaining_peak": f"lead_to_{quantity}_peak_sec",
            "time_to_highmotion_threshold_crossing": f"{quantity}_highmotion_crossing_lead_sec",
        }
        for definition, column in definitions.items():
            raw = pd.to_numeric(tail[column], errors="coerce").to_numpy(float)
            raw = raw[np.isfinite(raw)]
            if raw.size == 0:
                continue
            for latency in latencies:
                net = raw - float(latency)
                rows.append(
                    {
                        "quantity": quantity,
                        "lead_definition": definition,
                        "assumed_total_latency_sec": float(latency),
                        "n_with_defined_lead": int(raw.size),
                        "fraction_positive_net_lead": float(np.mean(net > 0.0)),
                        "fraction_net_lead_ge_1s": float(np.mean(net >= 1.0)),
                        "fraction_net_lead_ge_2s": float(np.mean(net >= 2.0)),
                        "fraction_net_lead_ge_5s": float(np.mean(net >= 5.0)),
                        "median_net_lead_sec": float(np.median(net)),
                    }
                )
    return pd.DataFrame(rows)


def metrics_by_peak_lead(
    frame: pd.DataFrame,
    edges: list[float],
    repetitions: int,
    confidence: float,
    seed: int,
    minimum_events: int,
) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    for quantity_index, quantity in enumerate(("pga", "pgv")):
        lead_column = f"lead_to_{quantity}_peak_sec"
        bin_column = f"{quantity}_peak_lead_bin"
        work = frame.loc[frame[f"is_tail_{quantity}"]].copy()
        work[bin_column] = make_lead_bins(work[lead_column], edges)
        for bin_index, (lead_bin, subset) in enumerate(
            work.groupby(bin_column, observed=True, sort=False)
        ):
            for metric_index, metric in enumerate(("mae", "under05", "bias", "factor2")):
                event_table = event_table_for_subset(subset, quantity, metric)
                result = bootstrap_paired_event_table(
                    event_table,
                    repetitions=repetitions,
                    confidence=confidence,
                    seed=seed + 1000 * quantity_index + 100 * bin_index + metric_index,
                )
                rows.append(
                    {
                        "quantity": quantity,
                        "lead_bin": str(lead_bin),
                        "median_lead_sec": float(pd.to_numeric(subset[lead_column], errors="coerce").median()),
                        "metric": metric,
                        "cross_attention_value": result.base,
                        "cross_attention_ci_lower": result.base_low,
                        "cross_attention_ci_upper": result.base_high,
                        "ca_urc_value": result.final,
                        "ca_urc_ci_lower": result.final_low,
                        "ca_urc_ci_upper": result.final_high,
                        "delta_caurc_minus_base": result.delta,
                        "delta_ci_lower": result.delta_low,
                        "delta_ci_upper": result.delta_high,
                        "relative_change_percent": (
                            100.0 * result.delta / abs(result.base)
                            if metric == "mae" and abs(result.base) > 1e-12
                            else np.nan
                        ),
                        "delta_percentage_points": (
                            100.0 * result.delta
                            if metric in {"under05", "factor2"}
                            else np.nan
                        ),
                        "bootstrap_p_two_sided": result.p_two_sided,
                        "bootstrap_probability_caurc_better": result.probability_final_better,
                        "n_events": result.n_events,
                        "n_sequence_groups": result.n_sequence_groups,
                        "n_target_rows": int(len(subset)),
                        "bootstrap_mode": result.mode,
                        "display_eligible": bool(result.n_events >= minimum_events),
                    }
                )
    return pd.DataFrame(rows)


def minimum_lead_effects(
    frame: pd.DataFrame,
    minimum_leads: list[float],
    repetitions: int,
    confidence: float,
    seed: int,
) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    for quantity_index, quantity in enumerate(("pga", "pgv")):
        lead_column = f"lead_to_{quantity}_peak_sec"
        tail = frame.loc[frame[f"is_tail_{quantity}"]].copy()
        for threshold_index, minimum_lead in enumerate(minimum_leads):
            if np.isclose(minimum_lead, 0.0):
                subset = tail.loc[pd.to_numeric(tail[lead_column], errors="coerce") > 0.0].copy()
                threshold_label = ">0"
            else:
                subset = tail.loc[
                    pd.to_numeric(tail[lead_column], errors="coerce") >= float(minimum_lead)
                ].copy()
                threshold_label = f"≥{minimum_lead:g}"
            for metric_index, metric in enumerate(("mae", "under05")):
                event_table = event_table_for_subset(subset, quantity, metric)
                result = bootstrap_paired_event_table(
                    event_table,
                    repetitions=repetitions,
                    confidence=confidence,
                    seed=seed + 5000 + 1000 * quantity_index + 100 * threshold_index + metric_index,
                )
                rows.append(
                    {
                        "quantity": quantity,
                        "minimum_peak_lead_sec": float(minimum_lead),
                        "minimum_peak_lead_label": threshold_label,
                        "metric": metric,
                        "cross_attention_value": result.base,
                        "ca_urc_value": result.final,
                        "delta_caurc_minus_base": result.delta,
                        "delta_ci_lower": result.delta_low,
                        "delta_ci_upper": result.delta_high,
                        "relative_change_percent": (
                            100.0 * result.delta / abs(result.base)
                            if metric == "mae" and abs(result.base) > 1e-12
                            else np.nan
                        ),
                        "delta_percentage_points": (
                            100.0 * result.delta if metric == "under05" else np.nan
                        ),
                        "bootstrap_p_two_sided": result.p_two_sided,
                        "bootstrap_probability_caurc_better": result.probability_final_better,
                        "n_events": result.n_events,
                        "n_sequence_groups": result.n_sequence_groups,
                        "n_target_rows": int(len(subset)),
                        "bootstrap_mode": result.mode,
                    }
                )
    return pd.DataFrame(rows)


def style_axis(ax: plt.Axes, grid_axis: str = "both") -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.set_axisbelow(True)
    if grid_axis == "x":
        ax.grid(axis="x", linewidth=0.45, alpha=0.24)
    elif grid_axis == "y":
        ax.grid(axis="y", linewidth=0.45, alpha=0.24)
    elif grid_axis == "both":
        ax.grid(linewidth=0.45, alpha=0.20)


