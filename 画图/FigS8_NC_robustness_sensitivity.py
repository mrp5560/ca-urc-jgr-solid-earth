def parse_bool(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.fillna(False).astype(bool)
    text = series.astype(str).str.strip().str.lower()
    true_values = {"true", "1", "yes", "y", "t"}
    false_values = {"false", "0", "no", "n", "f", "nan", "none", ""}
    unknown = set(text.unique()).difference(true_values | false_values)
    if unknown:
        raise ValueError(f"Cannot parse boolean values: {sorted(unknown)[:20]}")
    return text.isin(true_values)


def require_columns(frame: pd.DataFrame, columns: Iterable[str], name: str) -> None:
    missing = [column for column in columns if column not in frame.columns]
    if missing:
        raise ValueError(f"{name} is missing required columns: {missing}")


def finite_float(value: object, default: float = np.nan) -> float:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return default
    return out if np.isfinite(out) else default


def canonical_lead_bin(value: object) -> str:
    text = str(value).strip()
    replacements = {
        "–": "-",
        "—": "-",
        "−": "-",
        "s": "",
        " ": "",
        "≥": ">=",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    if text.startswith(">20"):
        text = ">=20"
    if text in {"20+", "20-inf", "20-infinity", "20-∞"}:
        text = ">=20"
    if text not in LEAD_ORDER:
        raise ValueError(
            f"Unsupported lead bin {value!r}; expected one of {LEAD_ORDER}."
        )
    return text


def style_axis(axis: plt.Axes, grid: str = "y") -> None:
    axis.spines["top"].set_visible(False)
    axis.spines["right"].set_visible(False)
    axis.set_axisbelow(True)
    if grid == "x":
        axis.grid(axis="x", linewidth=0.55, alpha=0.22)
    elif grid == "y":
        axis.grid(axis="y", linewidth=0.55, alpha=0.22)
    elif grid == "both":
        axis.grid(linewidth=0.5, alpha=0.18)


