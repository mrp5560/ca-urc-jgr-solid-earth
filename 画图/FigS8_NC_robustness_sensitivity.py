def write_manuscript(
    gamma_scan: pd.DataFrame,
    selected: pd.Series,
    lead: pd.DataFrame,
    balance: pd.DataFrame,
    caliper: pd.DataFrame,
    bootstrap: pd.DataFrame,
    out_path: Path,
) -> None:
    feasible_n = int(gamma_scan["feasible"].sum())
    total_n = int(len(gamma_scan))
    gamma_max = float(gamma_scan["gamma"].max())

    pga_lead = lead.loc[lead["quantity"].eq("pga")]
    pgv_lead = lead.loc[lead["quantity"].eq("pgv")]
    pga_min, pga_max = pga_lead["reduction_percent"].min(), pga_lead["reduction_percent"].max()
    pgv_min, pgv_max = pgv_lead["reduction_percent"].min(), pgv_lead["reduction_percent"].max()
    lead_all_mae_supported = bool(
        (lead["delta_ci_upper"] < 0.0).all()
    )

    def longest(q: str) -> pd.Series:
        return lead.loc[lead["quantity"].eq(q) & lead["lead_bin"].eq(">=20")].iloc[0]

    pga_long = longest("pga")
    pgv_long = longest("pgv")

    caliper_support = []
    for q in ("pga", "pgv"):
        sub = caliper.loc[caliper["quantity"].eq(q)]
        caliper_support.append(bool((sub["ci_upper"] < 0.0).all()))
    all_calipers_supported = all(caliper_support)

    bootstrap_support = []
    for q in ("pga", "pgv"):
        sub = bootstrap.loc[bootstrap["quantity"].eq(q)]
        bootstrap_support.append(bool((sub["ci_upper"] < 0.0).all()))
    both_bootstrap_supported = all(bootstrap_support)

    caliper_values = sorted(balance["caliper_km"].unique())
    pair_counts = {
        float(row.caliper_km): int(row.matched_pairs)
        for row in balance.itertuples(index=False)
    }

    if all_calipers_supported:
        caliper_sentence = (
            "The unseen-station tail-MAE effect retained a confidence interval below zero "
            f"under all three matching calipers ({', '.join(f'{v:g}' for v in caliper_values)} km), "
            "indicating that the conclusion was not determined by the primary 20-km choice."
        )
    else:
        caliper_sentence = (
            "Point estimates at the unseen stations remained favourable across the matching-caliper "
            "analysis, but at least one caliper-specific confidence interval included zero; the "
            "station result should therefore be interpreted as strongest under the prespecified "
            "20-km primary analysis rather than invariant to every matching choice."
        )

    if both_bootstrap_supported:
        bootstrap_sentence = (
            "For both PGA and PGV, the high-motion-tail MAE interval remained below zero under both "
            "the hierarchical sequence-to-event and the more conservative sequence-cluster bootstrap."
        )
    else:
        bootstrap_sentence = (
            "The point estimate remained favourable under both sequence-aware resampling schemes, "
            "but at least one sequence-cluster interval included zero; inferential strength therefore "
            "depends partly on how between-sequence variation is represented."
        )

    timing_sentence = (
        "All six warning-lead bins supported lower tail MAE for both quantities."
        if lead_all_mae_supported
        else "Tail-MAE point estimates were favourable across warning-lead bins, although at least one interval included zero."
    )

    text = f"""## Primary conclusions are not confined to a single gate setting or warning-time regime

We finally examined whether the primary tail-risk result depended on an isolated validation setting or a narrow subset of the physical warning-time distribution. The underprediction-risk correction head was evaluated over {total_n} validation-only epoch–gate-exponent combinations while the Cross-Attention Base remained frozen. Candidate configurations were required to satisfy the prespecified catalogue-wide MAE, non-tail MAE and bias safeguards for both PGA and PGV. Of these combinations, {feasible_n} were feasible. The final configuration was selected at epoch {int(selected['epoch'])} with $\\gamma={float(selected['gamma']):g}$ and did not occur at the upper boundary of the scanned range ($\\gamma={gamma_max:g}$; Supplementary Fig. S8a). The selected point was therefore not the only configuration satisfying the preservation constraints, although the validation scan should not be interpreted as independent test evidence for every candidate.

The reduction in high-motion-tail MAE was also distributed across the full range of time remaining before the target-station peak (Supplementary Fig. S8b). Across the six non-overlapping lead-time bins from 0–1 s to at least 20 s, relative PGA tail-MAE reductions ranged from {pga_min:.1f}% to {pga_max:.1f}%, whereas PGV reductions ranged from {pgv_min:.1f}% to {pgv_max:.1f}%. {timing_sentence} Even in the $\\geq20$-s subset, the paired changes were {float(pga_long['delta_caurc_minus_base']):+.3f} log10 units for PGA (95% confidence interval, {float(pga_long['delta_ci_lower']):+.3f} to {float(pga_long['delta_ci_upper']):+.3f}) and {float(pgv_long['delta_caurc_minus_base']):+.3f} for PGV ({float(pgv_long['delta_ci_lower']):+.3f} to {float(pgv_long['delta_ci_upper']):+.3f}). Thus, the aggregate improvement was not driven solely by targets whose remaining peaks occurred immediately after the causal snapshot.

Robustness to the station-matching definition was assessed using 10-, 20- and 30-km nearest-input-distance calipers while enforcing exact target P-wave-state matching and excluding all outcome variables from pair construction. The three analyses retained {pair_counts.get(10.0, 0):,}, {pair_counts.get(20.0, 0):,} and {pair_counts.get(30.0, 0):,} matched target pairs, respectively, while preserving all {int(balance['matched_events'].max())} test earthquakes (Supplementary Fig. S8c). {caliper_sentence} {bootstrap_sentence} (Supplementary Fig. S8d and Supplementary Table 8).

Together, these analyses show that the observed tail-MAE reduction is not confined to one feasible gate setting or one warning-lead stratum. They do not, however, establish invariance to every modelling decision. Observation-budget, tail-definition and independent-training-seed experiments are reported separately only after their corresponding models have been trained and locked; the present sensitivity analysis does not substitute for those experiments.
"""
    out_path.write_text(text, encoding="utf-8")


def write_required_experiments(out_path: Path) -> None:
    text = """REMAINING ROBUSTNESS EXPERIMENTS REQUIRED BEFORE A STRONG NATURE COMMUNICATIONS CLAIM

1. Observation budget (requires separate leakage-safe training for every setting)
   Recommended scenarios already supported by the manifest builder:
     T0=3 s, K=3
     T0=5 s, K=5  [primary]
     T0=10 s, K=5
     T0=10 s, K=10
   Do not evaluate the T0=5/K=5 checkpoint directly on a different feature horizon and call it
   robustness. Retrain and validation-lock the Base and CA-URC head within every scenario.

2. Tail definition
   Repeat the full train-only threshold construction and validation-only selection for Q85, Q90
   and Q95. Re-labelling the locked test set without retraining the risk head is not equivalent.

3. Severe-underprediction label
   Repeat the risk-head training for residual thresholds -0.3, -0.5 and -0.7 log10 units.
   Keep the primary endpoint (-0.5) unchanged and treat the others as sensitivity analyses.

4. Independent training seeds
   Prefer at least five independent seeds for both the Cross-Attention Base and the CA-URC head.
   Report seed-wise overall MAE, tail MAE, U0.5, selected epoch and selected gamma. The 20 target
   resampling repeats are not substitutes for independent model-training seeds.

5. Optional grouping sensitivity
   Rebuild sequence groups using nearby time/distance thresholds around the primary 30-day/30-km
   rule and repeat the grouped evaluation. This tests dependence on the leakage-control definition.

Until these runs exist, do not write that the method is robust to observation budget, tail quantile,
underprediction threshold or random initialization.
"""
    out_path.write_text(text, encoding="utf-8")


def table_to_latex(frame: pd.DataFrame, path: Path) -> None:
    path.write_text(frame.to_latex(index=False, escape=False, float_format=lambda x: f"{x:.4f}"), encoding="utf-8")


def write_outputs(
    gamma_scan: pd.DataFrame,
    selected: pd.Series,
    gamma_summary: pd.DataFrame,
    lead: pd.DataFrame,
    balance: pd.DataFrame,
    caliper: pd.DataFrame,
    bootstrap: pd.DataFrame,
    out_dir: Path,
) -> None:
    selection_table = gamma_summary.copy()
    selection_table["selected_gamma"] = np.isclose(selection_table["gamma"], float(selected["gamma"]))
    selection_table["selected_epoch"] = np.where(selection_table["selected_gamma"], int(selected["epoch"]), np.nan)
    selection_table.to_csv(out_dir / "TableS8_validation_selection.csv", index=False)
    table_to_latex(selection_table, out_dir / "TableS8_validation_selection.tex")

    lead_out = lead[
        [
            "quantity",
            "lead_bin",
            "cross_attention_value",
            "ca_urc_value",
            "delta_caurc_minus_base",
            "delta_ci_lower",
            "delta_ci_upper",
            "reduction_percent",
            "reduction_ci_lower",
            "reduction_ci_upper",
            "n_events",
        ]
    ].copy()
    lead_out.to_csv(out_dir / "TableS8_lead_time_sensitivity.csv", index=False)
    table_to_latex(lead_out, out_dir / "TableS8_lead_time_sensitivity.tex")

    caliper_out = caliper[
        [
            "caliper_km",
            "quantity",
            "n_events",
            "point_delta",
            "ci_lower",
            "ci_upper",
            "improvement",
            "matched_pairs",
            "matched_events",
            "median_abs_distance_difference_km",
        ]
    ].copy()
    caliper_out.to_csv(out_dir / "TableS8_station_caliper_sensitivity.csv", index=False)
    table_to_latex(caliper_out, out_dir / "TableS8_station_caliper_sensitivity.tex")

    bootstrap_out = bootstrap[
        [
            "quantity",
            "bootstrap_mode",
            "point_delta_candidate_minus_reference",
            "ci_lower",
            "ci_upper",
        ]
    ].copy()
    bootstrap_out.to_csv(out_dir / "TableS8_bootstrap_scheme_sensitivity.csv", index=False)
    table_to_latex(bootstrap_out, out_dir / "TableS8_bootstrap_scheme_sensitivity.tex")


