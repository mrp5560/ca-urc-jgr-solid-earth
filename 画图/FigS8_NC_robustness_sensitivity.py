def prepare_gamma_scan(path: Path) -> tuple[pd.DataFrame, pd.Series, pd.DataFrame]:
    frame = pd.read_csv(path)
    require_columns(frame, ["epoch", "gamma"], "gamma scan")

    if "mean_tail_mae" not in frame.columns:
        require_columns(frame, ["tail_mae_pga", "tail_mae_pgv"], "gamma scan")
        frame["mean_tail_mae"] = 0.5 * (
            pd.to_numeric(frame["tail_mae_pga"], errors="coerce")
            + pd.to_numeric(frame["tail_mae_pgv"], errors="coerce")
        )
    if "mean_tail_under05" not in frame.columns:
        if {"tail_under05_pga", "tail_under05_pgv"}.issubset(frame.columns):
            frame["mean_tail_under05"] = 0.5 * (
                pd.to_numeric(frame["tail_under05_pga"], errors="coerce")
                + pd.to_numeric(frame["tail_under05_pgv"], errors="coerce")
            )
        else:
            frame["mean_tail_under05"] = np.nan
    if "mean_overall_mae" not in frame.columns:
        require_columns(frame, ["overall_mae_pga", "overall_mae_pgv"], "gamma scan")
        frame["mean_overall_mae"] = 0.5 * (
            pd.to_numeric(frame["overall_mae_pga"], errors="coerce")
            + pd.to_numeric(frame["overall_mae_pgv"], errors="coerce")
        )
    if "feasible" not in frame.columns:
        raise ValueError(
            "Gamma scan must contain a validation-only 'feasible' column. "
            "Do not reconstruct feasibility from test performance."
        )

    frame["epoch"] = pd.to_numeric(frame["epoch"], errors="raise").astype(int)
    frame["gamma"] = pd.to_numeric(frame["gamma"], errors="raise").astype(float)
    frame["feasible"] = parse_bool(frame["feasible"])

    metric_columns = ["mean_tail_mae", "mean_tail_under05", "mean_overall_mae"]
    for column in metric_columns:
        frame[column] = pd.to_numeric(frame[column], errors="coerce")

    feasible = frame.loc[frame["feasible"]].copy()
    if feasible.empty:
        raise RuntimeError("No feasible validation candidates were found.")

    selected = feasible.sort_values(
        ["mean_tail_mae", "mean_tail_under05", "mean_overall_mae", "gamma", "epoch"],
        ascending=True,
        na_position="last",
    ).iloc[0]

    if int(selected["epoch"]) != LOCKED_EPOCH or not np.isclose(
        float(selected["gamma"]), LOCKED_GAMMA
    ):
        raise RuntimeError(
            "Validation scan does not reproduce the locked final selection: "
            f"observed epoch={int(selected['epoch'])}, gamma={float(selected['gamma']):g}; "
            f"expected epoch={LOCKED_EPOCH}, gamma={LOCKED_GAMMA:g}."
        )

    gamma_summary = (
        feasible.groupby("gamma", as_index=False)
        .agg(
            feasible_candidates=("epoch", "size"),
            minimum_mean_tail_mae=("mean_tail_mae", "min"),
            median_mean_tail_mae=("mean_tail_mae", "median"),
            p10_mean_tail_mae=("mean_tail_mae", lambda s: float(np.nanpercentile(s, 10))),
            p90_mean_tail_mae=("mean_tail_mae", lambda s: float(np.nanpercentile(s, 90))),
        )
        .sort_values("gamma")
    )
    return frame, selected, gamma_summary


def prepare_lead_sensitivity(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path)
    require_columns(
        frame,
        [
            "quantity",
            "lead_bin",
            "metric",
            "cross_attention_value",
            "ca_urc_value",
            "delta_caurc_minus_base",
            "delta_ci_lower",
            "delta_ci_upper",
            "n_events",
        ],
        "lead-bin table",
    )
    frame["quantity"] = frame["quantity"].astype(str).str.lower()
    frame["metric"] = frame["metric"].astype(str).str.lower()
    frame = frame.loc[
        frame["quantity"].isin(["pga", "pgv"]) & frame["metric"].eq("mae")
    ].copy()
    if "display_eligible" in frame.columns:
        frame = frame.loc[parse_bool(frame["display_eligible"])].copy()
    frame["lead_bin"] = frame["lead_bin"].map(canonical_lead_bin)

    for column in [
        "cross_attention_value",
        "ca_urc_value",
        "delta_caurc_minus_base",
        "delta_ci_lower",
        "delta_ci_upper",
    ]:
        frame[column] = pd.to_numeric(frame[column], errors="raise")
    frame["n_events"] = pd.to_numeric(frame["n_events"], errors="raise").astype(int)

    if frame.duplicated(["quantity", "lead_bin"]).any():
        raise ValueError("Lead-bin table contains duplicate quantity/bin rows.")

    # Positive values denote a reduction in tail MAE.
    frame["reduction_percent"] = (
        -100.0
        * frame["delta_caurc_minus_base"]
        / frame["cross_attention_value"].abs().clip(lower=1e-12)
    )
    frame["reduction_ci_lower"] = (
        -100.0
        * frame["delta_ci_upper"]
        / frame["cross_attention_value"].abs().clip(lower=1e-12)
    )
    frame["reduction_ci_upper"] = (
        -100.0
        * frame["delta_ci_lower"]
        / frame["cross_attention_value"].abs().clip(lower=1e-12)
    )
    frame["lead_order"] = frame["lead_bin"].map({v: i for i, v in enumerate(LEAD_ORDER)})
    return frame.sort_values(["quantity", "lead_order"])


def prepare_caliper_sensitivity(
    balance_path: Path, bootstrap_path: Path
) -> tuple[pd.DataFrame, pd.DataFrame]:
    balance = pd.read_csv(balance_path)
    bootstrap = pd.read_csv(bootstrap_path)
    require_columns(
        balance,
        [
            "caliper_km",
            "matched_events",
            "matched_pairs",
            "median_abs_distance_difference_km",
        ],
        "matching-balance table",
    )
    require_columns(
        bootstrap,
        [
            "caliper_km",
            "comparison_type",
            "group_or_model",
            "quantity",
            "population",
            "metric",
            "n_events",
            "point_delta",
            "ci_lower",
            "ci_upper",
        ],
        "matching bootstrap table",
    )

    for frame in (balance, bootstrap):
        frame["caliper_km"] = pd.to_numeric(frame["caliper_km"], errors="raise")

    effect = bootstrap.loc[
        bootstrap["comparison_type"].astype(str).str.lower().eq("caurc_minus_base")
        & bootstrap["group_or_model"].astype(str).str.lower().eq("unseen_station_target")
        & bootstrap["population"].astype(str).str.lower().eq("high_motion_tail")
        & bootstrap["metric"].astype(str).str.lower().eq("mae")
        & bootstrap["quantity"].astype(str).str.lower().isin(["pga", "pgv"])
    ].copy()
    effect["quantity"] = effect["quantity"].astype(str).str.lower()
    if effect.empty:
        raise ValueError(
            "No unseen-station high-motion-tail MAE rows were found in the matching bootstrap table."
        )
    if effect.duplicated(["caliper_km", "quantity"]).any():
        raise ValueError("Matching bootstrap contains duplicate caliper/quantity rows.")

    effect = effect.merge(
        balance[
            [
                "caliper_km",
                "matched_events",
                "matched_pairs",
                "median_abs_distance_difference_km",
            ]
        ],
        on="caliper_km",
        how="left",
        validate="many_to_one",
    )
    effect["improvement"] = -pd.to_numeric(effect["point_delta"], errors="raise")
    effect["improvement_ci_lower"] = -pd.to_numeric(effect["ci_upper"], errors="raise")
    effect["improvement_ci_upper"] = -pd.to_numeric(effect["ci_lower"], errors="raise")
    return balance.sort_values("caliper_km"), effect.sort_values(["quantity", "caliper_km"])


def prepare_bootstrap_sensitivity(path: Path) -> pd.DataFrame:
    frame = pd.read_csv(path)
    require_columns(
        frame,
        [
            "candidate",
            "reference",
            "quantity",
            "population",
            "metric",
            "bootstrap_mode",
            "point_delta_candidate_minus_reference",
            "ci_lower",
            "ci_upper",
        ],
        "sequence-aware bootstrap table",
    )
    candidate = frame["candidate"].astype(str).str.lower().str.replace("-", "_", regex=False)
    reference = frame["reference"].astype(str).str.lower().str.replace("-", "_", regex=False)
    mode = frame["bootstrap_mode"].astype(str).str.lower()
    out = frame.loc[
        candidate.isin({"ca_urc", "caurc", "a4_under_only"})
        & reference.isin({"cross_attention", "cross_attention_base", "s3"})
        & frame["quantity"].astype(str).str.lower().isin(["pga", "pgv"])
        & frame["population"].astype(str).str.lower().eq("high_motion_tail")
        & frame["metric"].astype(str).str.lower().eq("mae")
        & mode.isin({"hierarchical_sequence_event", "sequence_cluster"})
    ].copy()
    out["quantity"] = out["quantity"].astype(str).str.lower()
    out["bootstrap_mode"] = mode.loc[out.index]
    if out.duplicated(["quantity", "bootstrap_mode"]).any():
        raise ValueError("Duplicate quantity/bootstrap-mode rows were found.")
    expected = {(q, m) for q in ("pga", "pgv") for m in ("hierarchical_sequence_event", "sequence_cluster")}
    observed = set(zip(out["quantity"], out["bootstrap_mode"]))
    if observed != expected:
        raise ValueError(
            "Bootstrap table must contain both hierarchical_sequence_event and "
            f"sequence_cluster rows for PGA and PGV. Missing: {sorted(expected-observed)}"
        )
    for column in ["point_delta_candidate_minus_reference", "ci_lower", "ci_upper"]:
        out[column] = pd.to_numeric(out[column], errors="raise")
    return out.sort_values(["quantity", "bootstrap_mode"])


