def make_figure(
    gamma_scan: pd.DataFrame,
    selected: pd.Series,
    lead: pd.DataFrame,
    balance: pd.DataFrame,
    caliper: pd.DataFrame,
    bootstrap: pd.DataFrame,
    out_dir: Path,
    dpi: int,
    demo: bool,
) -> None:
    setup_matplotlib()
    cycle = plt.rcParams["axes.prop_cycle"].by_key()["color"]
    q_color = {"pga": cycle[0], "pgv": cycle[1]}

    fig, axes = plt.subplots(2, 2, figsize=(7.32, 5.55))
    ax_a, ax_b, ax_c, ax_d = axes.ravel()

    # a: validation-only selection landscape.
    feasible = gamma_scan.loc[gamma_scan["feasible"]].copy()
    infeasible = gamma_scan.loc[~gamma_scan["feasible"]].copy()
    ax_a.scatter(
        infeasible["gamma"],
        infeasible["mean_tail_mae"],
        s=8,
        alpha=0.10,
        linewidths=0,
        label="Constraint-violating",
    )
    ax_a.scatter(
        feasible["gamma"],
        feasible["mean_tail_mae"],
        s=9,
        alpha=0.32,
        linewidths=0,
        label="Feasible",
    )
    by_gamma = feasible.groupby("gamma", as_index=False)["mean_tail_mae"].min().sort_values("gamma")
    ax_a.plot(by_gamma["gamma"], by_gamma["mean_tail_mae"], linewidth=1.2, marker="o", markersize=2.8)
    ax_a.scatter(
        [float(selected["gamma"])],
        [float(selected["mean_tail_mae"])],
        marker="*",
        s=100,
        edgecolor="black",
        linewidth=0.6,
        zorder=8,
        label="Locked selection",
    )
    ax_a.set_xscale("log")
    gamma_ticks = sorted(gamma_scan["gamma"].unique())
    ax_a.set_xticks(gamma_ticks)
    ax_a.set_xticklabels([f"{g:g}" for g in gamma_ticks], rotation=45, ha="right")
    ax_a.set_xlabel(r"Gate exponent, $\gamma$")
    ax_a.set_ylabel("Mean validation tail MAE")
    ax_a.set_title("Validation-only gate selection")
    ax_a.text(
        0.98,
        0.98,
        f"{len(feasible)}/{len(gamma_scan)} feasible\nselected: epoch {int(selected['epoch'])}, $\\gamma$={float(selected['gamma']):g}",
        transform=ax_a.transAxes,
        ha="right",
        va="top",
        fontsize=7.2,
        bbox={"boxstyle": "round,pad=0.24", "facecolor": "white", "alpha": 0.86, "linewidth": 0.45},
    )
    style_axis(ax_a, "both")
    panel_label(ax_a, "a")

    # b: warning-lead strata.
    x = np.arange(len(LEAD_ORDER), dtype=float)
    offsets = {"pga": -0.12, "pgv": 0.12}
    for q in ("pga", "pgv"):
        sub = lead.loc[lead["quantity"].eq(q)].set_index("lead_bin").reindex(LEAD_ORDER)
        if sub["reduction_percent"].isna().any():
            raise ValueError(f"Lead table is incomplete for {q}.")
        y = sub["reduction_percent"].to_numpy(float)
        lo = y - sub["reduction_ci_lower"].to_numpy(float)
        hi = sub["reduction_ci_upper"].to_numpy(float) - y
        ax_b.errorbar(
            x + offsets[q],
            y,
            yerr=np.vstack([lo, hi]),
            marker="o" if q == "pga" else "s",
            markersize=4.0,
            linewidth=1.1,
            capsize=2.2,
            color=q_color[q],
            label=QUANTITY_LABEL[q],
        )
    ax_b.axhline(0.0, linewidth=0.8, color="0.25")
    ax_b.set_xticks(x)
    ax_b.set_xticklabels(["0-1", "1-2", "2-5", "5-10", "10-20", r"$\geq$20"])
    ax_b.set_xlabel("Time to remaining peak (s)")
    ax_b.set_ylabel("Tail-MAE reduction (%)")
    ax_b.set_title("Benefit across warning-lead strata")
    ax_b.legend(frameon=False, loc="upper right")
    style_axis(ax_b, "y")
    panel_label(ax_b, "b")

    # c: station matching calipers.
    for q in ("pga", "pgv"):
        sub = caliper.loc[caliper["quantity"].eq(q)].sort_values("caliper_km")
        y = sub["improvement"].to_numpy(float)
        lo = y - sub["improvement_ci_lower"].to_numpy(float)
        hi = sub["improvement_ci_upper"].to_numpy(float) - y
        ax_c.errorbar(
            sub["caliper_km"],
            y,
            yerr=np.vstack([lo, hi]),
            marker="o" if q == "pga" else "s",
            markersize=4.2,
            linewidth=1.2,
            capsize=2.3,
            color=q_color[q],
            label=QUANTITY_LABEL[q],
        )
    ax_c.axhline(0.0, linewidth=0.8, color="0.25")
    ax_c.set_xticks(sorted(balance["caliper_km"].unique()))
    ax_c.set_xlabel("Matching caliper (km)")
    ax_c.set_ylabel(r"Tail-MAE improvement ($\log_{10}$ units)")
    ax_c.set_title("Unseen-station matching sensitivity")
    # Put retained-pair counts above the larger of the two confidence intervals
    # at each caliper, rather than against the title.
    for row in balance.sort_values("caliper_km").itertuples(index=False):
        x_value = float(row.caliper_km)
        at_x = caliper.loc[np.isclose(caliper["caliper_km"], x_value)]
        y_anchor = float(at_x["improvement_ci_upper"].max())
        ax_c.annotate(
            f"n={int(row.matched_pairs):,}",
            xy=(x_value, y_anchor),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=6.7,
            clip_on=False,
        )
    ymin, ymax = ax_c.get_ylim()
    ax_c.set_ylim(ymin, ymax + 0.08 * (ymax - ymin))
    ax_c.legend(frameon=False, loc="lower right")
    style_axis(ax_c, "y")
    panel_label(ax_c, "c")

    # d: bootstrap scheme sensitivity.
    scheme_label = {
        "hierarchical_sequence_event": "Hierarchical sequence-event",
        "sequence_cluster": "Sequence-cluster",
    }
    rows = []
    for q in ("pga", "pgv"):
        for mode in ("hierarchical_sequence_event", "sequence_cluster"):
            row = bootstrap.loc[
                bootstrap["quantity"].eq(q) & bootstrap["bootstrap_mode"].eq(mode)
            ].iloc[0]
            rows.append((q, mode, row))
    y_positions = np.arange(len(rows))[::-1]
    for ypos, (q, mode, row) in zip(y_positions, rows):
        point = float(row["point_delta_candidate_minus_reference"])
        low = float(row["ci_lower"])
        high = float(row["ci_upper"])
        marker = "o" if mode == "hierarchical_sequence_event" else "D"
        ax_d.errorbar(
            point,
            ypos,
            xerr=np.array([[point - low], [high - point]]),
            marker=marker,
            markersize=4.6,
            linewidth=1.1,
            capsize=2.2,
            color=q_color[q],
        )
    ax_d.axvline(0.0, linewidth=0.8, color="0.25")
    ax_d.set_yticks(y_positions)
    # Keep the row labels compact so this panel remains legible at two-column width.
    ax_d.set_yticklabels(
        [
            f"{QUANTITY_LABEL[q]} · "
            + ("H" if m == "hierarchical_sequence_event" else "C")
            for q, m, _ in rows
        ]
    )
    ax_d.set_xlabel(r"CA-URC - Base tail MAE ($\log_{10}$ units)")
    ax_d.set_title("Inference under two resampling schemes")
    style_axis(ax_d, "x")
    panel_label(ax_d, "d")

    marker_legend = [
        Line2D([0], [0], marker="o", linestyle="none", color="0.25", label="H: hierarchical sequence–event"),
        Line2D([0], [0], marker="D", linestyle="none", color="0.25", label="C: sequence-cluster"),
    ]
    ax_d.legend(handles=marker_legend, frameon=False, loc="lower left", fontsize=6.8)

    if demo:
        fig.text(
            0.5,
            0.995,
            "LAYOUT PREVIEW - SYNTHETIC VALUES - NOT FOR MANUSCRIPT USE",
            ha="center",
            va="top",
            fontsize=9.0,
            fontweight="bold",
        )

    fig.subplots_adjust(left=0.095, right=0.985, bottom=0.105, top=0.93, wspace=0.39, hspace=0.42)
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = out_dir / "FigS8_robustness_sensitivity"
    fig.savefig(stem.with_suffix(".png"), dpi=dpi, bbox_inches="tight")
    fig.savefig(stem.with_suffix(".pdf"), bbox_inches="tight")
    fig.savefig(stem.with_suffix(".svg"), bbox_inches="tight")
    plt.close(fig)


