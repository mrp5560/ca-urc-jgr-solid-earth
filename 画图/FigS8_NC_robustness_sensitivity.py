def demo_inputs(seed: int = 20260713):
    rng = np.random.default_rng(seed)
    gammas = np.array([1, 1.5, 2, 2.5, 3, 4, 5, 6, 7, 8, 10, 12, 15, 20], float)
    rows = []
    for epoch in range(1, 41):
        for gamma in gammas:
            score = 0.61 + 0.00018 * (epoch - 3) ** 2 + 0.0018 * (np.log1p(gamma) - np.log1p(5)) ** 2
            score += rng.normal(0, 0.006)
            feasible = rng.random() < 0.64
            rows.append(
                {
                    "epoch": epoch,
                    "gamma": gamma,
                    "mean_tail_mae": score,
                    "mean_tail_under05": 0.52 + rng.normal(0, 0.015),
                    "mean_overall_mae": 0.30 + rng.normal(0, 0.002),
                    "feasible": feasible,
                }
            )
    gamma = pd.DataFrame(rows)
    gamma.loc[:, "feasible"] = False
    chosen = rng.choice(gamma.index, size=355, replace=False)
    gamma.loc[chosen, "feasible"] = True
    locked_index = gamma.index[(gamma.epoch == 3) & np.isclose(gamma.gamma, 5.0)][0]
    gamma.loc[locked_index, ["feasible", "mean_tail_mae", "mean_tail_under05", "mean_overall_mae"]] = [
        True,
        0.598,
        0.520,
        0.300,
    ]
    # Ensure the locked point is selected in demo.
    gamma.loc[gamma.index != locked_index, "mean_tail_mae"] = np.maximum(
        gamma.loc[gamma.index != locked_index, "mean_tail_mae"], 0.600
    )

    lead_rows = []
    for q, center in (("pga", 12.0), ("pgv", 15.5)):
        for i, b in enumerate(LEAD_ORDER):
            reduction = center + rng.normal(0, 2.0)
            base = 0.60 + 0.05 * i
            delta = -base * reduction / 100.0
            lead_rows.append(
                {
                    "quantity": q,
                    "lead_bin": b,
                    "metric": "mae",
                    "cross_attention_value": base,
                    "ca_urc_value": base + delta,
                    "delta_caurc_minus_base": delta,
                    "delta_ci_lower": delta - 0.012,
                    "delta_ci_upper": delta + 0.012,
                    "n_events": int(55 - 5 * i),
                    "display_eligible": True,
                }
            )
    lead = pd.DataFrame(lead_rows)

    balance = pd.DataFrame(
        {
            "caliper_km": [10.0, 20.0, 30.0],
            "matched_events": [195, 195, 195],
            "matched_pairs": [3248, 5649, 7148],
            "median_abs_distance_difference_km": [5.121, 8.897, 11.986],
        }
    )
    boot_rows = []
    for c in [10.0, 20.0, 30.0]:
        for q, d in (("pga", -0.060), ("pgv", -0.058)):
            jitter = rng.normal(0, 0.004)
            point = d + jitter
            boot_rows.append(
                {
                    "caliper_km": c,
                    "comparison_type": "caurc_minus_base",
                    "group_or_model": "unseen_station_target",
                    "quantity": q,
                    "population": "high_motion_tail",
                    "metric": "mae",
                    "n_events": 35 if q == "pga" else 30,
                    "point_delta": point,
                    "ci_lower": point - 0.018,
                    "ci_upper": point + 0.018,
                }
            )
    station_boot = pd.DataFrame(boot_rows)

    scheme_rows = []
    for q, d in (("pga", -0.072), ("pgv", -0.099)):
        for mode_name, width in (("hierarchical_sequence_event", 0.012), ("sequence_cluster", 0.030)):
            scheme_rows.append(
                {
                    "candidate": "ca_urc",
                    "reference": "cross_attention",
                    "quantity": q,
                    "population": "high_motion_tail",
                    "metric": "mae",
                    "bootstrap_mode": mode_name,
                    "point_delta_candidate_minus_reference": d,
                    "ci_lower": d - width,
                    "ci_upper": d + width,
                }
            )
    schemes = pd.DataFrame(scheme_rows)
    return gamma, lead, balance, station_boot, schemes


